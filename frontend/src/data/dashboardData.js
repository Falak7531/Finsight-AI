export const CURRENCIES = {
  INR: { code: 'INR', symbol: '₹', locale: 'en-IN', rate: 1 },
  USD: { code: 'USD', symbol: '$', locale: 'en-US', rate: 0.012 },
  EUR: { code: 'EUR', symbol: '€', locale: 'de-DE', rate: 0.011 },
}

export function formatMoney(amountInINR, currencyCode = 'INR') {
  const cfg = CURRENCIES[currencyCode] || CURRENCIES.INR
  const converted = Math.round(amountInINR * cfg.rate)
  return `${cfg.symbol}${Math.abs(converted).toLocaleString(cfg.locale)}`
}

